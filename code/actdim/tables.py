# ---------------------------------------------------------------- the LaTeX reader

_RULES = ("\\toprule", "\\midrule", "\\bottomrule", "\\cmidrule", "\\addlinespace",
          "\\morecmidrules", "\\hline")

# Macros whose braced argument is the text, and which contribute nothing else.
_UNWRAP = ("texttt", "textbf", "textit", "emph", "mathrm", "mathit", "text", "operatorname",
           "cref", "Cref", "ref", "label", "multirow", "boldmath")

_ESCAPES = (("\\_", "_"), ("\\&", "&"), ("\\%", "%"), ("\\#", "#"), ("\\{", "{"),
            ("\\}", "}"), ("\\$", "$"))

_THIN = ("\\,", "\\!", "\\;", "\\:", "\\/")
_SPACES = ("\\quad", "\\qquad", "\\ ", "~", "\\hspace")

_MISSING = ("---", "--", "\u2014", "\u2013")


def _strip_rules(text: str) -> str:
    for rule in _RULES:
        text = re.sub(re.escape(rule) + r"(\([a-z]{1,2}\))?(\{[^}]*\})?", "", text)
    return text


class ParseError(RuntimeError):
    """A table this reader will not guess at."""


@dataclass
class Cell:
    """One cell, cleaned of the formatting macros this document uses."""

    text: Optional[str]          # None where the article prints a dash
    raw: str
    column: int                  # first logical column this cell covers
    span: int = 1

    @property
    def missing(self) -> bool:
        return self.text is None


@dataclass
class Row:
    cells: List[Cell]
    line: int

    def at(self, column: int) -> Optional[Cell]:
        for cell in self.cells:
            if cell.column <= column < cell.column + cell.span:
                return cell
        return None

    def label(self) -> str:
        for cell in self.cells:
            if cell.text:
                return cell.text
        return ""

    @property
    def width(self) -> int:
        return sum(cell.span for cell in self.cells)


@dataclass
class Table:
    """One ``tabular`` block, as rows of cleaned cells."""

    label: str
    spec: str
    rows: List[Row]
    header_rows: int
    line: int

    def cell(self, row: int, column: int) -> Optional[Cell]:
        if not 0 <= row < len(self.rows):
            return None
        return self.rows[row].at(column)

    def printed(self, row: int, column: int) -> Optional[str]:
        cell = self.cell(row, column)
        return None if cell is None else cell.text

    def find(self, needle: str, start: int = 0) -> int:
        """The index of the first row whose label contains ``needle``.

        Checks are written against the article's own row labels rather than against row
        numbers, so that inserting a row above does not silently shift every check.
        """
        for i in range(start, len(self.rows)):
            if _norm(needle) in _norm(self.rows[i].label()):
                return i
        raise ParseError(f"{self.label}: no row labelled {needle!r}")

    def find_all(self, needle: str) -> List[int]:
        return [i for i, row in enumerate(self.rows)
                if _norm(needle) in _norm(row.label())]

    def body(self) -> List[int]:
        """Row indices below the header, skipping full-width section headings."""
        width = max(row.width for row in self.rows)
        return [i for i in range(self.header_rows, len(self.rows))
                if not (len(self.rows[i].cells) == 1 and self.rows[i].cells[0].span >= width)]

    def column_label(self, column: int) -> str:
        parts: List[str] = []
        for i in range(self.header_rows):
            cell = self.rows[i].at(column)
            if cell is not None and cell.text and (cell.span > 1 or i == self.header_rows - 1):
                parts.append(cell.text)
        return " / ".join(parts) if parts else f"column {column}"


def _norm(text: str) -> str:
    """A label reduced to what identifies it.

    The arithmetic operators are kept. Without them the two perceptron rows of
    ``tab:grok-diagnostics``, ``n+m`` and ``n \\cdot m``, reduce to the same string and a
    check aimed at one silently reads the other.
    """
    return re.sub(r"[^a-z0-9+*^<>=]+", "", text.lower())


def read_tables(path: Optional[Path] = None) -> Dict[str, Table]:
    """Every labelled ``tabular`` in the article, by label.

    A block whose rows do not agree on a width is refused rather than guessed at: a
    mis-parsed row would put a computed value beside the wrong printed one, which is a
    worse failure than not checking the table at all.
    """
    source = (path or article_path()).read_text(encoding="utf-8")
    tables: Dict[str, Table] = {}
    label = ""
    lines = source.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        found = re.search(r"\\label\{(tab:[^}]+)\}", line)
        if found:
            label = found.group(1)
        if "\\begin{tabular}" in line:
            start = i
            depth = 0
            block: List[Tuple[int, str]] = []
            while i < len(lines):
                if "\\begin{tabular}" in lines[i]:
                    depth += 1
                if depth:
                    block.append((i + 1, lines[i]))
                if "\\end{tabular}" in lines[i]:
                    depth -= 1
                    if depth == 0:
                        break
                i += 1
            if label:
                tables[label] = _parse_block(label, block, start + 1)
            label = ""
        i += 1
    return tables


def _parse_block(label: str, block: Sequence[Tuple[int, str]], line: int) -> Table:
    spec = ""
    opening = re.search(r"\\begin\{tabular\}\s*(?:\[[^\]]*\])?\{([^}]*)\}", block[0][1])
    if opening:
        spec = opening.group(1)

    # Strip the delimiters, then rejoin physical lines: one logical row runs to its `\\`.
    body: List[Tuple[int, str]] = []
    for number, text in block:
        text = re.sub(r"\\begin\{tabular\}\s*(?:\[[^\]]*\])?\{[^}]*\}", "", text)
        text = text.replace("\\end{tabular}", "")
        text = re.sub(r"(?<!\\)%.*$", "", text)
        body.append((number, text))

    rows: List[Row] = []
    header_rows = 0
    seen_midrule = False
    buffer: List[str] = []
    buffer_line = body[0][0]
    for number, text in body:
        # The line a row is reported on is the line its *content* starts on. A `\midrule`
        # or an `\addlinespace` sitting alone above a row is buffered with it, and taking
        # the line the buffer opened on would point every such row at the rule above it.
        # Nothing downstream would notice: the row still parses, and only an edit made at
        # the reported line lands in the wrong row.
        if not any(_strip_rules(part).strip() for part in buffer):
            buffer_line = number
        while True:
            split = re.search(r"\\\\", text)
            if not split:
                buffer.append(text)
                break
            buffer.append(text[:split.start()])
            row = _parse_row("".join(buffer), buffer_line)
            if row is not None:
                rows.append(row)
                if not seen_midrule:
                    header_rows = len(rows)
            buffer = []
            text = text[split.end():]
            buffer_line = number
        if rows and not seen_midrule and re.search(r"\\midrule", text):
            seen_midrule = True
    tail = _parse_row("".join(buffer), buffer_line)
    if tail is not None:
        rows.append(tail)

    if not rows:
        raise ParseError(f"{label}: no rows")
    if not seen_midrule:
        header_rows = 1
    return Table(label=label, spec=spec, rows=rows, header_rows=header_rows, line=line)


def _parse_row(text: str, line: int) -> Optional[Row]:
    stripped = text.strip()
    if not stripped:
        return None
    stripped = _strip_rules(stripped)
    if not stripped.strip():
        return None

    cells: List[Cell] = []
    column = 0
    for raw in _split_ampersands(stripped):
        span, inner = _span_of(raw)
        cells.append(Cell(text=_clean(inner), raw=raw.strip(), column=column, span=span))
        column += span
    return Row(cells=cells, line=line)


def _split_ampersands(text: str) -> List[str]:
    parts: List[str] = []
    depth = 0
    current: List[str] = []
    i = 0
    while i < len(text):
        char = text[i]
        if char == "\\" and i + 1 < len(text):
            current.append(text[i:i + 2])
            i += 2
            continue
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
        if char == "&" and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(char)
        i += 1
    parts.append("".join(current))
    return parts


def _span_of(raw: str) -> Tuple[int, str]:
    found = re.search(r"\\multicolumn\s*\{(\d+)\}\s*\{[^}]*\}\s*", raw)
    if not found:
        return 1, raw
    rest = raw[found.end():]
    inner, after = _braced(rest)
    return int(found.group(1)), raw[:found.start()] + inner + after


def _braced(text: str) -> Tuple[str, str]:
    """Split ``{a}b`` into ``a`` and ``b``, respecting nesting."""
    text = text.lstrip()
    if not text.startswith("{"):
        return "", text
    depth = 0
    for i, char in enumerate(text):
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return text[1:i], text[i + 1:]
    return text[1:], ""


def _clean(raw: str) -> Optional[str]:
    text = raw
    for macro in _UNWRAP:
        while True:
            found = re.search(r"\\" + macro + r"\s*(\{\d+\}\s*\{[^}]*\}\s*)?", text)
            if not found:
                break
            inner, after = _braced(text[found.end():])
            text = text[:found.start()] + inner + after
    for old, new in _ESCAPES:
        text = text.replace(old, new)
    text = re.sub(r"\\phantom\s*\{[^}]*\}", "", text)
    for macro in _THIN:
        text = text.replace(macro, "")
    for macro in _SPACES:
        text = text.replace(macro, " ")
    text = text.replace("$", "")
    text = text.replace("{=}", "=").replace("\\times", "x").replace("\\cdot", "*")
    # A macro that survives this far keeps its name: `\tau` is the row label of tab:tau and
    # `\PR_{\mathrm{delay}}` names a row of tab:alts, so dropping the name would leave two
    # rows called the same nothing and no check could name the one it means.
    text = re.sub(r"\\([a-zA-Z]+)", r"\1", text)
    text = text.replace("{", "").replace("}", "")
    text = re.sub(r"\s+", " ", text).strip()
    if text in _MISSING or text == "":
        return None if text in _MISSING else ""
    return text


# ---------------------------------------------------------------- reading a printed cell

_NUMBER = re.compile(r"^[-+]?(\d+(\.\d*)?|\.\d+)([eE][-+]?\d+)?$")


def as_number(text: Optional[str]) -> Optional[float]:
    """The number a printed cell holds, or ``None`` if it does not hold one."""
    if text is None:
        return None
    body = text.strip().replace(",", "")
    if body.endswith("k") and _NUMBER.match(body[:-1] or "x"):
        return float(body[:-1]) * 1000.0
    if not _NUMBER.match(body):
        return None
    return float(body)


def decimals(text: str) -> int:
    """How many decimal places the article printed, which sets the comparison."""
    body = text.strip().replace(",", "")
    if body.endswith("k"):
        return 0
    if "." not in body:
        return 0
    return len(body.split(".")[1].rstrip())


def round_half_up(value: float, places: int) -> float:
    quantum = Decimal(1).scaleb(-places)
    return float(Decimal(repr(float(value))).quantize(quantum, rounding=ROUND_HALF_UP))


# ---------------------------------------------------------------- the report

OK = "ok"
ROUNDING = "rounding"
MISMATCH = "mismatch"
UNREADABLE = "unreadable"


CELL = "cell"
CLAIM = "claim"


@dataclass
class Finding:
    """One cell that was compared, or one claim that was settled, and how it came out."""

    label: str
    row: str
    column: str
    printed: Optional[str]
    computed: Optional[float]
    source: str
    status: str
    note: str = ""
    kind: str = CELL
    provenance: str = ""

    @property
    def bad(self) -> bool:
        return self.status in (ROUNDING, MISMATCH)

    def describe(self) -> str:
        if self.kind == CLAIM:
            return (f"{self.label:22s} {self.row[:26]:26s} claim                  "
                    f"article: {self.printed}\n"
                    f"{'':22s} {'':26s} {'':22s} files:   {self.computed}  {self.source}")
        printed = "---" if self.printed is None else self.printed
        if self.computed is None:
            got = "no value"
        elif isinstance(self.computed, str):
            got = self.computed
        else:
            got = f"{self.computed:.6f}".rstrip("0").rstrip(".")
        detail = f"  ({self.note})" if self.note else ""
        return (f"{self.label:22s} {self.row[:26]:26s} {self.column[:22]:22s} "
                f"printed {printed:>10s}  computed {got:>14s}  {self.source}{detail}")


@dataclass
class TableResult:
    label: str
    state: str                                    # "checked" or "skipped"
    reason: str = ""
    findings: List[Finding] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)

    @property
    def mismatches(self) -> List[Finding]:
        return [f for f in self.findings if f.bad]

    @property
    def checked(self) -> int:
        return len(self.findings)


@dataclass
class Report:
    results: List[TableResult]
    article: str = ""
    data: str = ""
    inputs: Dict[str, str] = field(default_factory=dict)

    @property
    def mismatches(self) -> List[Finding]:
        return [f for result in self.results for f in result.mismatches]

    @property
    def ok(self) -> bool:
        return not self.mismatches

    def by_label(self, label: str) -> TableResult:
        for result in self.results:
            if result.label == label:
                return result
        raise KeyError(label)

    @property
    def archived_inputs(self) -> List[str]:
        return sorted(name for name, source in self.inputs.items() if source == ARCHIVED)

    def rows(self) -> List[Dict[str, Any]]:
        """The report as a list of records, one per compared cell or settled claim.

        This is what ``check.tables`` writes as a CSV, so the fields are flat and ``status``
        is one of the four comparison constants, or ``"skipped"``. A skipped table
        contributes one row carrying its reason, so that the file says which tables were not
        checked as well as which cells disagreed: a checker that finds nothing to check and
        says nothing is wrong is the failure this whole module exists to prevent.
        """
        out: List[Dict[str, Any]] = []
        for result in self.results:
            if result.state == "skipped":
                out.append({"table": result.label, "kind": "table", "row": "",
                            "column": "", "printed": "", "computed": "", "source": "",
                            "provenance": "", "status": result.state, "note": result.reason})
                continue
            for finding in result.findings:
                out.append({
                    "table": finding.label,
                    "kind": finding.kind,
                    "row": finding.row,
                    "column": finding.column,
                    "printed": "" if finding.printed is None else finding.printed,
                    "computed": _as_text(finding.computed),
                    "source": finding.source,
                    "provenance": finding.provenance,
                    "status": finding.status,
                    "note": finding.note,
                })
        return out


def _provenance_of(source: str, read: Dict[str, str]) -> str:
    """How the files behind one finding got into ``data/``.

    A source string can name more than one file, so every recorded input the string mentions
    is looked up and the distinct answers are joined. ``archived`` in the result means the
    cell was checked against the numbers the article was written from rather than against a
    regeneration, which is weaker evidence and has to be visible as such.
    """
    found = [state for name, state in read.items() if name in source]
    if not found:
        return read.get(source, "")
    return " + ".join(sorted(set(found)))


def _as_text(value: Any) -> str:
    """A computed value at full precision, which is what the report has to show beside the
    printed one: rounding it here would hide exactly the disagreement being reported."""
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, (list, tuple)):
        return ", ".join(_as_text(v) for v in value)
    return repr(float(value))


# ---------------------------------------------------------------- the data side

ARCHIVED = "archived"
REGENERATED = "regenerated"
UNLISTED = "not in the manifest"
CODE = "code"


class Data:
    """The tracked half of the tree, read once per file, with its provenance kept.

    Every read is recorded against what ``data/manifest.json`` says produced the file. A
    table checked against an archived file has been checked against the numbers the article
    was written from, not against a regeneration, and the report has to say which, or the
    check reads as stronger evidence than it is.
    """

    def __init__(self, root: Optional[Path] = None):
        self.root = root or data_root()
        self._frames: Dict[str, pd.DataFrame] = {}
        self._objects: Dict[str, Any] = {}
        self._manifest = load_manifest().get("files", {}) if self.root == data_root() else {}
        self.read: Dict[str, str] = {}

    def has(self, rel: str) -> bool:
        return (self.root / rel).exists()

    def require(self, rel: str) -> Path:
        path = self.root / rel
        if not path.exists():
            raise FileNotFoundError(f"data/{rel} is missing; run `actdim bootstrap` first")
        entry = self._manifest.get(rel, {})
        self.read[self.name(rel)] = (ARCHIVED if entry.get("source") == ARCHIVED
                                     else REGENERATED if entry else UNLISTED)
        return path

    def frame(self, rel: str) -> pd.DataFrame:
        if rel not in self._frames:
            self._frames[rel] = pd.read_csv(self.require(rel))
        else:
            self.require(rel)
        return self._frames[rel]

    def json(self, rel: str) -> Any:
        if rel not in self._objects:
            self._objects[rel] = json.loads(self.require(rel).read_text(encoding="utf-8"))
        else:
            self.require(rel)
        return self._objects[rel]

    def note_code(self, name: str) -> str:
        """Record a source that is a module of this package rather than a file in ``data/``.

        The run registry of appendix O is the only such source. It is code, so it is neither
        archived nor regenerated, and it is what the article's budget column is checked
        against because no committed file records the perceptron budgets.
        """
        self.read[name] = CODE
        return name

    @staticmethod
    def name(rel: str) -> str:
        return "data/" + rel


@dataclass
class Computed:
    """One recomputed cell, ready to be diffed against what the article prints.

    ``tolerance`` widens the comparison for a cell whose printed form is not a rounding of
    the computed one. The only use is a step index that falls between two logged steps: the
    S_5 runs log every five steps, so a window centre lands on 712.5 and the article prints
    712. Everything else compares at the precision printed and nothing else.
    """

    row: int
    column: int
    value: Any                                    # float, str, None, or a list of those
    source: str
    note: str = ""
    tolerance: float = 0.0
    column_name: str = ""
    """What to call the column in the report, where the header does not say.

    ``tab:ceiling`` is two scans stacked in one ``tabular``, so the second block's columns
    are headed by a row inside the body and the header above says ``E_max``. Left to the
    header, a disagreement in the record scan would be reported against an embedding
    dimension it has nothing to do with.
    """


@dataclass
class Claim:
    """A statement a caption or the surrounding text makes, which ``data/`` can settle.

    Three of the defects already on record are of this shape rather than the shape of a
    wrong cell: ``tab:alts``'s two columns are aggregated differently and the caption does
    not say so, ``tab:ladder``'s caption describes a sliding-window median for rows that
    have one window, and the text under ``tab:runs`` names the wrong four runs as the
    sketched ones. A checker that only compared cells would pass all three, so claims are
    checked here beside the cells and count the same way towards the exit status.
    """

    row: str                                      # what to call it in the report
    statement: str                                # what the article says
    holds: bool
    finding: str                                  # what the files say instead
    source: str


