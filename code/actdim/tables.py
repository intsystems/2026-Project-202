def _runs_named_below(table: Table, lines: int = 12) -> Tuple[str, ...]:
    """The ``\\texttt`` run names in the paragraph that follows a table.

    Reads the article rather than the table, because the sentence under ``tab:runs`` is
    the thing being checked and it is prose.
    """
    source = article_path().read_text(encoding="utf-8").split("\n")
    start = next((i for i in range(table.line, len(source))
                  if "\\end{table}" in source[i]), None)
    if start is None:
        return ()
    block = "\n".join(source[start + 1:start + 1 + lines])
    block = block.split("\n\n")[0] if "\n\n" in block else block
    found = re.findall(r"\\texttt\{([^}]*)\}", block)
    seen: List[str] = []
    for name in (n.replace("\\_", "_") for n in found):
        if name not in seen:
            seen.append(name)
    return tuple(seen)


def _budget(printed: Optional[str], reach: Any) -> Optional[float]:
    """The printed budget, confirmed or contradicted by how far the record runs.

    Returned as the printed value when the record reaches it, and as the reach itself when
    it does not, so that a truncated run shows up as a mismatch naming the step it stopped
    at rather than as a silent pass.
    """
    stated = as_number(printed)
    reached = _nan_to_none(reach)
    if stated is None or reached is None:
        return None
    return stated if reached >= stated * (1.0 - BUDGET_TOLERANCE) else reached


_EOS_RATES = (1e5, 3e5, 1e6, 1.5e6, 2e6, 2.5e6, 2.8e6, 3e6)


def check_eos(table: Table, data: Data) -> Iterable[Any]:
    runs = data.frame("train.perceptron.eos/eos_runs.csv")
    recurrence = data.frame("grok.eos/eos_recurrence.csv")
    run_file = Data.name("train.perceptron.eos/eos_runs.csv")
    recurrence_file = Data.name("grok.eos/eos_recurrence.csv")

    # A run is comparable only at the campaign's budget. The run key is the rate and the
    # seed, so a short pass writes the same key as the full one, and a record left behind
    # by such a pass reports a rate at the edge of stability as monotone -- nothing has
    # happened yet at step 200. Those rows are named rather than averaged in.
    budget = int(runs.max_steps.max())
    short = runs[runs.max_steps < budget]
    # Reported whether or not any run is short. A check that says nothing when it passes
    # cannot be told from a check that was never made, and this one was added because the
    # committed table had carried two 200-step rows among fourteen 30,000-step ones.
    yield Claim(
        row="the campaign budget",
        statement=f"every run is {budget:,} steps",
        holds=short.empty,
        finding=(f"all {len(runs)} runs are" if short.empty else
                 "; ".join(f"{r.key} ran {int(r.max_steps):,}"
                           for _, r in short.iterrows())
                 + ". Those runs are left out of the comparison below"),
        source=run_file)
    runs = runs[runs.max_steps >= budget]

    body = table.body()
    for row, rate in zip(body, _EOS_RATES):
        at_rate = runs[np.abs(runs.lr - rate) < 1.0].sort_values("seed")
        if at_rate.empty:
            continue
        ratios, rises, returns = [], [], []
        for _, record in at_rate.iterrows():
            if _nan_to_none(record.diverged_at) is not None:
                ratios.append(None)
                rises.append(None)
                returns.append(None)
                continue
            ratios.append(float(record.eta_lam_over_2_median_tail))
            seed = recurrence[(np.abs(recurrence.lr - rate) < 1.0)
                              & (recurrence.seed == record.seed)]
            rises.append(float(seed.rises.median()) if not seed.empty else None)
            returns.append(float(seed.nn_over_travel.median()) if not seed.empty else None)
        yield Computed(row, 1, _collapse(ratios), run_file)
        yield Computed(row, 2, _collapse(rises), recurrence_file)
        yield Computed(row, 3, _collapse(returns), recurrence_file)


def _collapse(values: List[Optional[float]]) -> Any:
    """A per-seed list, or ``None`` where every seed diverged and the article prints a dash."""
    return None if all(v is None for v in values) else values


