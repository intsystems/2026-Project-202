"""Append the protected-control results to the reproducible main report."""
from pathlib import Path
import json
import pandas as pd
H=Path(__file__).resolve().parent

def fmt(x,n=3):return f'{x:.{n}f}'.replace('.',',')

def integrate(text):
    s=json.loads((H/'summary.json').read_text())
    df=pd.read_csv(H/'all_seeds.csv').query('seed>0')
    valid=df[df.protection_valid]
    ci=s['median_R_valid_bootstrap95']
    interval='не определён' if ci is None else f'[{fmt(ci[0])}; {fmt(ci[1])}]'
    result=(f"**Дополнительный контроль сохранения кода:** критерий защиты выполнен в {len(valid)}/9 продолжений; "
        f"MG выше, чем при потере информации, в {s['protected_MG_higher_count']}/{len(valid)} из них "
        f"(медиана отношения по всей девятке {fmt(s['median_R_all'])}). Постановка и ограничения — раздел 5.")
    # Replace, rather than accumulate, the older claim of an untested control.
    old='Следующий содержательный контроль — то же изменение регуляризации с защитой от потери использования кода.'
    text=text.replace(old,'Контроль с сохранением значительной части информации теперь выполнен; см. раздел 5.')
    text=text.replace('**Что ещё не проверено:** специфичность детектора, преимущество перед KL',
        '**Что ещё не установлено:** универсальная специфичность детектора, преимущество перед KL')
    text=text.replace('## 4. Устойчивость, альтернативы и границы вывода',
        '## 4. Устойчивость, альтернативы и границы вывода\n\n'+result)
    table='\n'.join(f'| {label} | {fmt(df[f"MI_{arm}"].median())} | {fmt(df[f"shuffle_symkl_{arm}"].median())} | {fmt(df[f"MG_{arm}"].median())} | {fmt(1. if arm=="base" else df[f"q_{arm}"].median())} |'
        for arm,label in [('base','Исходный контроль'),('regularized','Усиление KL'),('protected','Усиление KL + free bits')])
    text+=f'''

<!-- pagebreak -->

## 5. Сохранение информации при том же внешнем коэффициенте KL

**Зачем этот контроль.** В исходном сравнении менялись одновременно коэффициент регуляризации и использование кода. Добавлена третья ветвь к каждому сохранённому состоянию на шаге 1024: тот же переход beta с 0,01 на 1, но с защитой кода. Это продолжения прежних десяти инициализаций; основные числа ниже — по seeds 1–9, пилот отдельно. Все ветви имеют одинаковые исходные веса, Adam, последовательность основных батчей и латентного шума.

**Выбор защиты без MG.** Пять дополнительных шагов encoder на пилоте не удержали код: информация упала с 5,48 до 0,52 нат. После этого применён заранее предусмотренный free bits: каждый средний по батчу KL отдельной координаты заменяется максимумом с 0,5 нат, затем значения суммируются по 16 координатам. Ниже порога штраф не создаёт градиента, подавляющего эту координату. Остальная процедура прежняя. Это изменение формы функции потерь, поэтому контроль не изолирует одну только величину beta.

Пилотная защита выбрана по независимым характеристикам, до расчёта её MG: поздняя информация и реакция на перестановку каждая должны сохранять не менее половины исходного уровня и превышать regularized минимум вдвое. Затем вариант зафиксирован для всех девяти остальных seed. Критерий выполнен в **{len(valid)}/9**; отбор по MG не проводился. Защита частичная, полного сохранения информации не предполагаем.

| Ветвь | Информация, нат | Реакция на код | MG | MG / base |
| --- | --- | --- | --- | --- |
{table}

Сначала берётся поздняя медиана внутри каждого seed, затем медиана по девяти seed. Последний столбец — медиана парных отношений, не отношение медиан предыдущего столбца. Поздний интервал — шаги 2048–3072; MG: окно 512, delay 1. Все индивидуальные тройки приведены в отдельном отчёте protection/report_ru.pdf.

![Три режима на девяти инициализациях](protection/comparison_cohort.pdf)

Медиана и межквартильный диапазон по seeds 1–9. Серый — base, синий — regularized, оранжевый — free bits. Сверху независимые показатели использования кода, снизу входной reconstruction loss и MG.

**Результат.** Среди успешных защит MG выше regularized в {s['protected_MG_higher_count']}/{len(valid)} и ближе к base в {s['closer_to_base_count']}/{len(valid)}. Медиана парного отношения protected/regularized по всей девятке — {fmt(s['median_R_all'])}; 95% bootstrap-интервал медианы среди успешных защит — {interval}. При этом медиана protected/base составляет {fmt(s['median_q_protected'])}, против {fmt(s['median_q_regularized'])} у regularized: защита не возвращает MG к исходному контролю.

**Как трактовать.** Различие MG согласуется с меньшей потерей информации в защищённой ветви в этой постановке. Это усиливает исходное наблюдение, но не доказывает, что любой спад MG означает потерю информации: информация сохранена лишь частично, а free bits меняет оптимизацию. Стандартное отклонение того же loss также выше при защите в {s['cheap_baselines'][0]['R_above_one']}/9: преимущество MG над простой статистикой не установлено. Дополнительные запуски не являются benchmark времени: они выполнялись параллельно.

Код, протокол до запусков, неудачная попытка encoder5, все десять защищённых ветвей и проверки сохранены в protection/. Предыдущая версия отчёта — before_protection/. Идея free bits: Kingma et al., Improved Variational Inference with Inverse Autoregressive Flow, NeurIPS 2016, Appendix C (arXiv 1606.04934).
'''
    return text
