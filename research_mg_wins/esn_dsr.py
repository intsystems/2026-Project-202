"""E10: model selection for learned simulators (dynamical systems reconstruction) by MG.

An echo state network (ESN) is trained by ridge regression to predict the next value of a
scalar series generated by a known system, then run in closed loop. Many hyperparameter
settings give a small one-step error yet the wrong long-run dynamics: the torus locks into
a cycle, the model decays to a point, or it turns chaotic. The practitioner's question:
which trained model to keep, using only the scalar series it generates.

Ground truth (expensive, uses the full model): the Lyapunov spectrum of the closed-loop map
plus a frequency/amplitude check of the generated series.
Selectors (cheap, scalar only): one-step validation error, valid prediction time, the
spectral Hellinger distance D_H of the DSR literature, and |stat(model) - stat(data)| for
MG and every competitor in baselines.py.

PROTOCOL (frozen after the pilot on T2, dseed 0, which looked only at the Lyapunov
classes, never at a selector; MG config chosen in calib_dsr.py on target signals only).

Confirmatory run: targets T2, T3 (tori, base period 40.37 steps, clean data) and Lorenz x
(dt 0.02); data seeds 1-3, reservoir seed 0 for every data seed; the 162-point grid over spectral
radius, input scale, leak and ridge; N = 300.

Ground truth "faithful", from the full model:
  torus Tq  output std within x[0.5, 2] of the data, lambda1 <= 0.003 per step, exactly q
            exponents >= -0.003 among the top six, and each true frequency within 1.5 %
            of one of the six strongest spectral peaks of the output;
  Lorenz    std within x[0.5, 2], lambda1 within [0.5, 1.5] x 0.0181 per step, and lambda2
            within +-0.003 (the zero exponent).
Candidate pool for every selector: models whose output is finite and whose std is within
x[0.5, 2] of the data (a check any practitioner makes).
Selectors: one-step validation MSE (min), valid prediction time (max), spectral Hellinger
distance D_H (min), and |s(model) - s(data)| (min) for s in MG, spectral entropy, self-repeat,
roughness, peak count, permutation entropy, recurrence rate, correlation dimension,
TwoNN, linear PR. All use only the scalar output.
Scores per (target, data seed): top-1 faithful, precision among the 5 best, AUC of
faithful vs unfaithful within the pool.
Predictions:
  P1  MG's mean AUC >= 0.8 and exceeds those of MSE, VPT and D_H;
  P2  MG's mean top-5 precision exceeds those of MSE, VPT and D_H;
  P3  MG picks a faithful model (top-1) in at least 7 of the 9 problems.
The geometric competitors (recurrence rate, correlation dimension, TwoNN) are reported
without a prediction.
"""
